// Build the production privilege contract and the ACL that enforces it.
//
//   node scripts/derive-service-role-acl.mjs <ghost privilege-manifest.expected.json>
//
// The contract is GHOST's final-state privilege manifest (production bundle
// v79, `supabase/tests/privilege-manifest.expected.json`) plus the explicit,
// reviewed decisions below for objects the PURE core carries that the manifest
// does not. Replaying the GHOST GRANT/REVOKE history was not enough: a later
// narrower GRANT never removes an earlier broader one, so DELETE/UPDATE
// survived on finance and history tables.
//
// Outputs:
//   database/production/privilege-contract.json  — what every object must allow
//   database/pure-service-role-acl.sql           — applied after pure-cloud-access.sql
//
// The public roles (PUBLIC, anon, authenticated) get nothing, ever: PURE's
// public visitors reach business data only through the server.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const manifestPath = process.argv[2];
if (!manifestPath) throw new Error("usage: derive-service-role-acl.mjs <privilege-manifest.expected.json>");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

const TABLE_PRIVILEGES = ["SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"];

/* Objects in the PURE core that the v79 manifest does not list. */
const SUPPLEMENT = {
  tables: {
    // GHOST customer-trial data plane; PURE never runs a trial, so closed.
    vip_manager_trial_baselines: [],
    vip_manager_trial_run_events: [],
    vip_manager_trial_runs: [],
  },
  functions: {
    // v80 (20260919120000_ghost_admin_open_business_day_v80.sql) grants these
    // to service_role; the VIP Manager's business-day, reservation and walk-in
    // routes call them.
    "ensure_admin_event_day_v80(uuid,text,text,text,date,text)": ["service_role"],
    "ensure_admin_booking_slots_v80(uuid)": ["service_role"],
    "create_admin_reservation_v23(uuid,text,text,text,uuid,uuid,timestamp with time zone,timestamp with time zone,integer,uuid[],jsonb,uuid,bytea,bytea,bytea,text,text,text,text,text,text,vip_service_status,uuid,text,boolean,text)": ["service_role"],
    "create_admin_walk_in_reservation_v23(uuid,text,text,text,uuid,uuid,timestamp with time zone,timestamp with time zone,integer,uuid[],text,text,jsonb,uuid,boolean,text)": ["service_role"],
    // Trial-only helpers: closed.
    "cleanup_vip_manager_trial_restricted_rows_v17(text)": [],
    "ghost_vip_stamp_trial_run_id_v16()": [],
    "ghost_vip_trial_run_id_v16()": [],
  },
  // v59 revoked every sequence and re-granted only the metrics insert path;
  // the two later sequences were never granted.
  sequences: {
    vip_manager_metrics_id_seq: ["SELECT", "USAGE"],
    ticket_sale_interruptions_id_seq: [],
    ticket_wallet_credential_audits_id_seq: [],
  },
};

const contract = { source: manifest.generatedFrom, tables: {}, functions: {}, sequences: SUPPLEMENT.sequences };
for (const [name, entry] of Object.entries(manifest.tables)) {
  contract.tables[name] = [...(entry.grants?.service_role ?? [])].filter((p) => TABLE_PRIVILEGES.includes(p)).sort();
}
for (const [name, privileges] of Object.entries(SUPPLEMENT.tables)) contract.tables[name] = privileges;
for (const [signature, entry] of Object.entries(manifest.functions)) {
  contract.functions[signature] = (entry.execute ?? []).includes("service_role");
}
for (const [signature, roles] of Object.entries(SUPPLEMENT.functions)) contract.functions[signature] = roles.includes("service_role");

const guarded = (statement) => [
  "DO $guard$ BEGIN",
  `  EXECUTE $acl$${statement}$acl$;`,
  "EXCEPTION WHEN undefined_function OR undefined_table OR undefined_object THEN NULL;",
  "END $guard$;",
].join("\n");

const lines = [
  "-- pure-service-role-acl.sql — GENERATED by scripts/derive-service-role-acl.mjs. Do not edit by hand.",
  `-- Contract: database/production/privilege-contract.json (${manifest.generatedFrom} + reviewed PURE supplement).`,
  "-- Apply AFTER pure-cloud-access.sql, in the same transaction.",
  "",
  "-- Start from zero, then grant exactly the contract.",
  "REVOKE ALL ON ALL TABLES IN SCHEMA public FROM service_role;",
  "REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM service_role;",
  "REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, service_role;",
  "",
];
for (const [name, privileges] of Object.entries(contract.tables).sort()) {
  if (privileges.length > 0) lines.push(guarded(`GRANT ${privileges.join(", ")} ON TABLE public.${name} TO service_role`));
}
for (const [signature, executable] of Object.entries(contract.functions).sort()) {
  if (executable) lines.push(guarded(`GRANT EXECUTE ON FUNCTION public.${signature} TO service_role`));
}
for (const [name, privileges] of Object.entries(contract.sequences).sort()) {
  if (privileges.length > 0) lines.push(guarded(`GRANT ${privileges.join(", ")} ON SEQUENCE public.${name} TO service_role`));
}
lines.push(
  "",
  "-- Future objects start closed; every migration grants explicitly (GHOST v59).",
  "-- Schema-level defaults remove Supabase's per-schema grants; the global",
  "-- defaults remove PostgreSQL's built-in PUBLIC EXECUTE on new functions, which a",
  "-- schema-level REVOKE cannot cancel.",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE ALL ON FUNCTIONS FROM anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;",
  "ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;",
  "",
);
const sql = lines.join("\n");
const contractJson = `${JSON.stringify(contract, null, 2)}\n`;
await writeFile("database/production/privilege-contract.json", contractJson);
await writeFile("database/pure-service-role-acl.sql", sql);
console.log(JSON.stringify({
  tables: Object.keys(contract.tables).length,
  functions: Object.keys(contract.functions).length,
  executable: Object.values(contract.functions).filter(Boolean).length,
  sequences: Object.keys(contract.sequences).length,
  aclSha256: createHash("sha256").update(sql).digest("hex"),
  contractSha256: createHash("sha256").update(contractJson).digest("hex"),
}));
